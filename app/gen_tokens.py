"""Generate app/static/tokens.css from app/tokens.json (design-token source of truth).

Run: python3 app/gen_tokens.py [output-path]
Stdlib only. Tokens use DTCG-style $type/$value; colors carry light/dark pairs.
"""
import json
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent


def pairs(group):
    for name, token in group.items():
        value = token.get("$value")
        if isinstance(value, dict):
            yield name, value.get("light", ""), value.get("dark", value.get("light", ""))
        else:
            yield name, value, value


def render(tokens):
    light, dark = [], []
    for name, light_value, dark_value in pairs(tokens.get("color", {})):
        light.append(f"  --{name}: {light_value};")
        if dark_value != light_value:
            dark.append(f"  --{name}: {dark_value};")
    for name, light_value, dark_value in pairs(tokens.get("shadow", {})):
        light.append(f"  --shadow-{name}: {light_value};")
        if dark_value != light_value:
            dark.append(f"  --shadow-{name}: {dark_value};")
    for name, token in tokens.get("font", {}).items():
        light.append(f"  --font-{name}: {token['$value']};")
    for name, token in tokens.get("text", {}).items():
        light.append(f"  --text-{name}: {token['$value']};")
    for name, token in tokens.get("duration", {}).items():
        light.append(f"  --duration-{name}: {token['$value']};")
    light.append(f"  --radius: {tokens['radius']['base']['$value']};")
    header = "/* Generated by app/gen_tokens.py from app/tokens.json — do not edit by hand. */"
    return (header + "\n:root {\n" + "\n".join(light) + "\n}\n.dark {\n" + "\n".join(dark) + "\n}\n")


def main():
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else APP_DIR / "static" / "tokens.css"
    tokens = json.loads((APP_DIR / "tokens.json").read_text())
    output.write_text(render(tokens))
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
